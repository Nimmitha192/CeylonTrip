import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { adminService } from '../../services/adminService';
import { useToast } from '../../context/ToastContext';
import { Luggage, Search, ExternalLink, Calendar, MapPin } from 'lucide-react';
import { formatCurrency, formatDate } from '../../utils/formatters';

export default function ManageTrips() {
  const [trips, setTrips] = useState([]);
  const [search, setSearch] = useState('');
  const [loading, setLoading] = useState(true);
  const { addToast } = useToast();

  const fetchTrips = async () => {
    setLoading(true);
    try {
      const res = await adminService.getTrips({ search });
      setTrips(res.data || []);
    } catch (err) {
      addToast('Error fetching trips', 'error');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchTrips();
  }, [search]);

  return (
    <div className="space-y-6">
      <div>
        <h1 className="font-display font-extrabold text-2xl sm:text-3xl text-slate-900">
          Platform Trips Catalog
        </h1>
        <p className="text-xs text-slate-500 mt-0.5">
          View all personalized itineraries generated by registered users.
        </p>
      </div>

      <div className="bg-white p-4 rounded-2xl border border-slate-200 shadow-soft">
        <div className="relative">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Search trips by title..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full pl-10 pr-4 py-2 text-xs rounded-xl border border-slate-200 focus:ring-2 focus:ring-emerald-500 focus:outline-none"
          />
        </div>
      </div>

      <div className="bg-white rounded-2xl border border-slate-200 shadow-soft overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-xs text-left">
            <thead className="bg-slate-50 text-slate-500 uppercase font-bold border-b">
              <tr>
                <th className="px-6 py-3.5">Trip Title</th>
                <th className="px-6 py-3.5">User</th>
                <th className="px-6 py-3.5">Duration</th>
                <th className="px-6 py-3.5">Starting Hub</th>
                <th className="px-6 py-3.5">Est. Cost</th>
                <th className="px-6 py-3.5">Created Date</th>
                <th className="px-6 py-3.5 text-right">View</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {loading ? (
                <tr>
                  <td colSpan="7" className="text-center py-8 text-slate-400">
                    Loading trips...
                  </td>
                </tr>
              ) : trips.length === 0 ? (
                <tr>
                  <td colSpan="7" className="text-center py-8 text-slate-400">
                    No trips logged.
                  </td>
                </tr>
              ) : (
                trips.map((t) => (
                  <tr key={t._id} className="hover:bg-slate-50">
                    <td className="px-6 py-3.5 font-bold text-slate-900">
                      {t.title}
                    </td>
                    <td className="px-6 py-3.5 text-slate-600">
                      {t.user?.name || 'Anonymous'}
                    </td>
                    <td className="px-6 py-3.5">
                      <span className="font-semibold text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded-md">
                        {t.duration} Days
                      </span>
                    </td>
                    <td className="px-6 py-3.5 text-slate-600">{t.startingLocation?.name}</td>
                    <td className="px-6 py-3.5 font-bold text-slate-800">
                      {formatCurrency(t.estimatedCost?.total)}
                    </td>
                    <td className="px-6 py-3.5 text-slate-400">{formatDate(t.createdAt)}</td>
                    <td className="px-6 py-3.5 text-right">
                      <Link
                        to={`/trips/${t._id}`}
                        target="_blank"
                        className="inline-flex items-center gap-1 p-1.5 rounded-lg text-slate-500 hover:text-emerald-700 hover:bg-emerald-50"
                        title="View Trip"
                      >
                        <ExternalLink className="w-3.5 h-3.5" />
                      </Link>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
